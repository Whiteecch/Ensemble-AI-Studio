def available_keys() -> list[str]:
    """框架的规范键集合（取自 zh-Hans 主目录，已排序）。"""
    return sorted(CATALOGS[DEFAULT_LANGUAGE])


def llm_language_directive(language: str) -> str:
    """给所有 LLM prompt 用的一行中文指令：指定作答语言。

    七个语言码全给非空指令，且**含该语言的母语名**；未知码回落默认语言（不抛）。
    """
    native = LANGUAGES.get(language)
    if native is None:
        native = LANGUAGES[DEFAULT_LANGUAGE]
    return f"你将使用{native}回答。"


class Translator:
    """按语言取文案。缺键回落主目录；主目录也缺 → 原样返回键（可见降级，不抛）。"""

    def __init__(self, language: str = DEFAULT_LANGUAGE) -> None:
        self._language = language if language in LANGUAGES else DEFAULT_LANGUAGE

    @property
    def language(self) -> str:
        return self._language

    def set_language(self, code: str) -> bool:
        """认识就切并返回 True；不认识则保持当前语言并返回 False。"""
        if code in LANGUAGES:
            self._language = code
            return True
        return False

    def _template(self, key: str) -> str | None:
        """取模板：当前语言 → zh-Hans 主目录 → None。"""
        hit = CATALOGS.get(self._language, {}).get(key)
        if hit is not None:
            return hit
        return CATALOGS[DEFAULT_LANGUAGE].get(key)

    @staticmethod
    def _format(template: str, fmt: dict) -> str:
        """给了 fmt 才 str.format；格式化失败（缺参/坏模板）原样返回，绝不抛。"""
        if not fmt:
            return template
        try:
            return template.format(**fmt)
        except (KeyError, IndexError, ValueError):
            return template

    def t(self, key: str, **fmt) -> str:
        """取键对应文案；缺键返回键本身。"""
        template = self._template(key)
        if template is None:
            return key
        return self._format(template, fmt)

    def t_or(self, key: str, fallback: str, **fmt) -> str:
        """取键对应文案；缺键返回 fallback（fallback 同样支持 fmt 占位）。"""
        template = self._template(key)
        if template is None:
            template = fallback
        return self._format(template, fmt)
